import type { Config } from 'tailwindcss';
import plugin from 'tailwindcss/plugin';

/**
 * Theme tokens for the 60s NASA-poster identity (spec §7 "Theme"): a muted
 * mission-patch palette, a serif display type scale borrowed from the printable
 * kit (`proposals/one-small-step-printable-kit.html`), and print helpers.
 *
 * Color is decorative only — every piece of information is carried by type or
 * by an icon paired with text, so the board reads correctly in greyscale.
 *
 * Breakpoints are Tailwind's defaults and map to the spec §7 tiers:
 *   mobile 360–640 (base) · tablet 640–1024 (md) · desktop 1024+ (lg) · wide (xl).
 */
export default {
  content: ['./index.html', './src/web/**/*.{ts,tsx}'],
  theme: {
    extend: {
      colors: {
        // Warm paper stock and ink — the kit's black-on-white, softened.
        paper: {
          DEFAULT: '#F3EEE2',
          deep: '#E6DECB',
          edge: '#D5CAB0',
        },
        ink: {
          DEFAULT: '#1C1A15',
          soft: '#4B463A',
          faint: '#7C7461',
        },
        // Muted mission-patch accents (decorative only).
        patch: {
          navy: '#21395C',
          red: '#9E3A2E',
          gold: '#B08A3E',
          teal: '#2E5A55',
        },
      },
      fontFamily: {
        // Display serif matches the printable kit's Georgia body copy.
        display: ['Georgia', "'Times New Roman'", 'serif'],
        body: [
          'ui-sans-serif',
          'system-ui',
          '-apple-system',
          "'Segoe UI'",
          'Roboto',
          'sans-serif',
        ],
      },
      fontSize: {
        micro: ['0.625rem', { lineHeight: '0.875rem', letterSpacing: '0.1em' }],
        label: ['0.6875rem', { lineHeight: '1rem', letterSpacing: '0.14em' }],
        title: ['1.125rem', { lineHeight: '1.35', letterSpacing: '0.06em' }],
        display: ['2rem', { lineHeight: '1.05', letterSpacing: '0.08em' }],
      },
      letterSpacing: {
        poster: '0.18em',
      },
      minHeight: {
        target: '2.75rem', // 44 px — spec §7 minimum touch target on mobile
      },
    },
  },
  plugins: [
    // Print surface: the on-screen board degrades to a readable sheet when
    // printed (spec §7 theme); the print kit itself is generated by src/print.
    plugin(({ addComponents, addUtilities }) => {
      addUtilities({
        '.print-page-break': { '@media print': { 'break-before': 'page' } },
      });
      addComponents({
        '.no-print': { '@media print': { display: 'none !important' } },
        '.print-only': { display: 'none', '@media print': { display: 'block' } },
        '.print-sheet': {
          '@media print': {
            color: '#000',
            background: '#fff',
            'font-family': "Georgia, 'Times New Roman', serif",
          },
        },
      });
    }),
  ],
} satisfies Config;
